    def _get_valhalla_matrix_param(self, sources, targets, costing):
        data = {"sources":sources,"targets":targets,"costing":costing}
        return quote(json.dumps(data, default=str))
    
    def parse_valhalla_to_df(self, data, row_labels, col_labels):
        # Erstellt eine 2D-Liste der Distanzen
        matrix = [
            [target['time'] for target in source] 
            for source in data['sources_to_targets']
        ]
        return pd.DataFrame(matrix, index=row_labels, columns=col_labels)
    
    def calc_depots_cost_matrix(self):
        depots_coords = [
            {"lat": geom.y, "lon": geom.x} 
            for geom in self.depots_gdf.geometry
        ]
        
        tours_start = []
        for geom in self.tours_gdf.geometry:
            if geom is None or geom.is_empty:
                continue
            if geom.geom_type == 'MultiLineString':
                # Nimm die erste Linie aus der Sammlung
                first_part = geom.geoms[0]
                lon, lat = first_part.coords[0]
                tours_start.append({"lat": lat, "lon": lon, "radius": 100})
            elif geom.geom_type == 'LineString':
                # Direkter Zugriff bei einfacher Linie
                lon, lat = geom.coords[0]
                tours_start.append({"lat": lat, "lon": lon, "radius": 100})
        
        tours_end = []
        for geom in self.tours_gdf.geometry:
            if geom is None or geom.is_empty:
                continue
            if geom.geom_type == 'MultiLineString':
                # Nimm die erste Linie aus der Sammlung
                first_part = geom.geoms[-1]
                lon, lat = first_part.coords[-1]
                tours_end.append({"lat": lat, "lon": lon, "radius": 100})
            elif geom.geom_type == 'LineString':
                # Direkter Zugriff bei einfacher Linie
                lon, lat = geom.coords[-1]
                tours_end.append({"lat": lat, "lon": lon, "radius": 100})
        
        # Kosten von Depots zu Transport-Starts berechnenen
        url = self.valhalla_url + '/sources_to_targets?json=' + self._get_valhalla_matrix_param(depots_coords,tours_start, "auto")
        response_start = requests.get(url)
        response_start.raise_for_status()
        start_data = response_start.json()
        
        # Kosten von Transport-Stops zu Depots berechnenen
        url = self.valhalla_url + '/sources_to_targets?json=' + self._get_valhalla_matrix_param(tours_end,depots_coords, "auto")
        response_end = requests.get(url)
        response_end.raise_for_status()
        end_data = response_end.json()
        
        # In Datenmodell überführen
        
        depot_ids = self.depots_gdf['id'].tolist()
        tour_ids = self.tours_gdf['id'].tolist()
        
        # Matrix: Zeilen = Depots, Spalten = Touren
        self.matrix_depot_to_start = self.parse_valhalla_to_df(start_data, depot_ids, tour_ids)

        # Matrix: Zeilen = Touren, Spalten = Depots
        self.matrix_end_to_depot = self.parse_valhalla_to_df(end_data, tour_ids, depot_ids)
        pass
    
    def calc_tours_cost_matrix(self):
        valid_indices = []
        tours_start = []
        tours_end = []
        
        for idx, geom in self.tours_gdf.geometry.items():
            if geom is None or geom.is_empty:
                continue
            
            if geom.geom_type == 'MultiLineString':
                # Startpunkt (erste Linie, erster Punkt)
                start_lon, start_lat = geom.geoms[0].coords[0]
                # Endpunkt (letzte Linie, letzter Punkt)
                end_lon, end_lat = geom.geoms[-1].coords[-1]
            elif geom.geom_type == 'LineString':
                start_lon, start_lat = geom.coords[0]
                end_lon, end_lat = geom.coords[-1]
            else:
                continue
            
            tours_start.append({"lat": start_lat, "lon": start_lon, "radius": 100})
            tours_end.append({"lat": end_lat, "lon": end_lon, "radius": 100})
            valid_indices.append(self.tours_gdf.loc[idx, "id"]) # Wir merken uns den Original-Index der Tour!
        
        # Abbruch, falls keine validen Touren gefunden wurden
        if not valid_indices:
            raise "No valid tours found"
        
        # 2. Valhalla API Aufruf
        # Quellen = tours_end (Ende der vorherigen Tour)
        # Ziele = tours_start (Start der nächsten Tour)
        url = f"{self.valhalla_url}/sources_to_targets?json={self._get_valhalla_matrix_param(tours_end, tours_start, 'auto')}"
        
        try:
            response_tour = requests.get(url)
            response_tour.raise_for_status()
            tours_data = response_tour.json()
        except requests.exceptions.RequestException as e:
            print(f"Fehler bei der Valhalla Matrix-Berechnung: {e}")
            raise e
        
        
        # 3. Zeit und Strecke in ein kombiniertes DataFrame schreiben
        matrix_data = tours_data.get('sources_to_targets', [])

        verbindungen = []

        for i, row in enumerate(matrix_data):
            von_tour_id = valid_indices[i]
            
            for j, cell in enumerate(row):
                nach_tour_id = valid_indices[j]
                
                # Zeit und Distanz auslesen
                fahrzeit = cell.get('time')
                strecke = cell.get('distance')
                
                verbindungen.append({
                    'start_tour_id': von_tour_id,
                    'end_tour_id': nach_tour_id,
                    'time': fahrzeit,
                    'distance': strecke
                })

        matrix_df = pd.DataFrame(verbindungen)

        # Einträge mit gleicher tour_id herausfiltern
        matrix_df = matrix_df[matrix_df['start_tour_id'] != matrix_df['end_tour_id']].reset_index(drop=True)

        self.matrix_tours_to_tours = matrix_df
        pass
    
    def fetch_valhalla_route_info(self, geom, valhalla_url):
    # Null-Werte abfangen
        if geom is None or geom.is_empty:
            return pd.Series([None, None])
            
        start = None
        end = None
        
        # Koordinaten extrahieren
        if geom.geom_type == 'MultiLineString':
            first_part = geom.geoms[0]
            lon_start, lat_start = first_part.coords[0]
            lon_end, lat_end = first_part.coords[-1]
            start = {"lat": lat_start, "lon": lon_start, "radius": 100}
            end = {"lat": lat_end, "lon": lon_end, "radius": 100}
        elif geom.geom_type == 'LineString':
            lon_start, lat_start = geom.coords[0]
            lon_end, lat_end = geom.coords[-1]
            start = {"lat": lat_start, "lon": lon_start, "radius": 100}
            end = {"lat": lat_end, "lon": lon_end, "radius": 100}
            
        if start is None or end is None:
            return pd.Series([None, None])
            
        # Valhalla Request vorbereiten
        data = {"locations": [start, end], "costing": "auto"}
        data_param = quote(json.dumps(data, default=str))
        url = f"{valhalla_url}/route?json={data_param}"
        
        try:
            response_tour = requests.get(url)
            response_tour.raise_for_status()
            tour_data = response_tour.json()
            
            # Daten aus Valhalla extrahieren (Einheiten: length in km, time in s)
            summary = tour_data.get('trip', {}).get('summary', {})
            distance = summary.get('length')
            time = summary.get('time')
            
            return pd.Series([distance, time])
            
        except requests.exceptions.RequestException as e:
            print(f"API Fehler bei Koordinaten {start} zu {end}: {e}")
            return pd.Series([None, None])
        
    def calc_tours_cost(self):
        self.tours_gdf[['distance_km', 'time_sec']] = self.tours_gdf.geometry.apply(
            lambda geom: self.fetch_valhalla_route_info(geom, self.valhalla_url)
        )
        pass

