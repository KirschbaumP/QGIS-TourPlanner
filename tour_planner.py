    def create_memory_layer(self, gdf, layer_name="Touren"):
        # 1. Geometrietyp und EPSG aus dem GDF auslesen
        geom_type = gdf.geom_type.iloc[0] # 'Point', 'LineString', 'Polygon'
        epsg = gdf.crs.to_epsg()
        
        # 2. Leeres Memory-Layer anlegen
        uri = f"{geom_type}?crs=epsg:{epsg}"
        layer = QgsVectorLayer(uri, layer_name, "memory")
        pr = layer.dataProvider()
        
        geom_col_name = gdf.geometry.name
        attribute_columns = [col for col in gdf.columns if col != geom_col_name]
        
        # 3. Datentypen mappen und QGIS-Felder anlegen
        qgs_fields = []
        for col in attribute_columns:
            dtype = gdf[col].dtype
            
            # Pandas Datentypen zu PyQt QVariant mappen
            if pd.api.types.is_integer_dtype(dtype):
                qtype = QVariant.Int
            elif pd.api.types.is_float_dtype(dtype):
                qtype = QVariant.Double
            elif pd.api.types.is_bool_dtype(dtype):
                qtype = QVariant.Bool
            elif pd.api.types.is_datetime64_any_dtype(dtype):
                qtype = QVariant.DateTime
            else:
                qtype = QVariant.String # Standard-Fallback
                
            qgs_fields.append(QgsField(str(col), qtype))
            
        # Felder dem Layer hinzufügen
        pr.addAttributes(qgs_fields)
        layer.updateFields() # Wichtig: Damit das Layer die neuen Felder "kennt"
        
        # 4. Features bauen (Geometrie als WKT übergeben)
        features = []
        for idx, row in gdf.iterrows():
            feat = QgsFeature()
            # shapely Geometrie zu WKT, dann zu QgsGeometry
            geom_wkt = row.geometry.wkt 
            feat.setGeometry(QgsGeometry.fromWkt(geom_wkt))
            
            # Attribute anhängen
            attrs = []
            for col in attribute_columns:
                val = row[col]
                
                # Fehlende Werte (NaN/None) als NULL an QGIS übergeben
                if pd.isna(val):
                    attrs.append(None)
                # NumPy Typen sicher in native Python Typen casten (QGIS mag oft keine np.int64)
                elif isinstance(val, (np.integer, int)):
                    attrs.append(int(val))
                elif isinstance(val, (np.floating, float)):
                    attrs.append(float(val))
                else:
                    attrs.append(str(val))
                    
            feat.setAttributes(attrs)
            features.append(feat)
            
        # 5. Features zum Layer hinzufügen und updaten
        pr.addFeatures(features)
        layer.updateExtents()
        
        QgsProject.instance().addMapLayer(layer)
        return layer